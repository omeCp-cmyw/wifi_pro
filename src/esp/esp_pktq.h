#ifndef ESP_PKTQ_H
#define ESP_PKTQ_H

#include <stdint.h>

#define ESP_PKTQ_NUM    8
#define ESP_PKTQ_SIZE   1024    /* 全量属性JSON+MQTT头留足余量 */

/* 发送结果: ok为1成功, 0重发耗尽失败 */
typedef void (*esp_pktq_done_cb_t)(int link, int ok, void *arg);

/*******************************************************************
** 函数名	: esp_pktq_init
** 函数描述	: 初始化静态包池并挂接SEND OK/SEND FAIL通知
** 参数		: 无
** 返回		: 无
********************************************************************/
void esp_pktq_init(void);

/*******************************************************************
** 函数名	: esp_pktq_enqueue
** 函数描述	: 拷贝数据入队, 由pump负责发CIPSEND与裸字节
** 参数		: [in] link: 链路号
**          : [in] data: 待发数据
**          : [in] len: 数据长度
**          : [in] retry: 失败重发次数(不含首次)
**          : [in] cb: 结果回调(可为NULL)
**          : [in] arg: 回调参数
** 返回		: 0成功, -1池满或参数非法
********************************************************************/
int esp_pktq_enqueue(int link, const uint8_t *data, int len, int retry,
                     esp_pktq_done_cb_t cb, void *arg);

/*******************************************************************
** 函数名	: esp_pktq_pump
** 函数描述	: 主循环周期调用, 推进各节点的发送状态机
** 参数		: 无
** 返回		: 无
********************************************************************/
void esp_pktq_pump(void);

/*******************************************************************
** 函数名	: esp_pktq_busy
** 函数描述	: 查询是否还有节点在途
** 参数		: 无
** 返回		: 1有在途包, 0空闲
********************************************************************/
int esp_pktq_busy(void);

#endif
